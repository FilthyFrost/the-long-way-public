"""ModCar engine banks: record every engine with the headless Engine Simulator recorder and cut the
takes into seamless loops and one-shots for src/game/modcar/engineAudio.ts.

    python -I tools/enginesim/make_banks.py record [ids...]   # run the recorder (parallel)
    python -I tools/enginesim/make_banks.py build  [ids...]   # cut, layer, level, encode, manifest
    python -I tools/enginesim/make_banks.py all    [ids...]

Paths (environment, defaults in brackets):
    MODCAR_ESIM      recorder build dir from prepare.mjs   [D:/modcar-scratch/sound/esim]
    MODCAR_RAW       raw takes                              [D:/modcar-scratch/sound/raw]
    MODCAR_FFMPEG    ffmpeg.exe                             [found on PATH or under D:/modcar-scratch/sound/dl-ffmpeg]

Every steady take is recorded with the dynamometer holding the crank speed, so nothing stalls and
the rpm of each loop is exact: 'on' = throttle wide open (the dyno absorbs the power), 'off' = the
overrun (throttle shut and spark on for the petrol engines; air open and fuel cut for the diesels),
which at the idle step is the idle itself.

A machine that never coasts (offMode 'light', the generator gen_d1) has its own plan (make_plan_light):
a few steps round its governed speed ('steps'), 'off' = a light-load run at 'offThrottle', the crank
on a hand pull with the air open, a start that never lets the dyno take hold of a kick-back, a stall
with the rack wide open, and no rev-limiter take ('limiterTake': false).

A vehicle engine may borrow from it (engines.json): 'forwardGrab' (a high-compression single diesel,
eng_d1, kicks back at its first firings: the start and the restart are taken by the dyno while the
starter turns the crank forwards, fuel off), 'catchRamp' (a heavy flywheel spins up slowly) and
'shutdownSeconds' (and runs down for longer).
"""
import glob
import json
import math
import os
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
ESIM = os.environ.get('MODCAR_ESIM', r'D:\modcar-scratch\sound\esim')
RAW = os.environ.get('MODCAR_RAW', r'D:\modcar-scratch\sound\raw')
OUT = os.path.join(REPO, 'public', 'audio', 'modcar', 'engines')
TABLE = json.load(open(os.path.join(HERE, 'engines.json'), encoding='utf8'))['engines']

SETTLE_ON = 1.2
SETTLE_OFF = 1.2
TAKE = 3.4


def rpm_steps(e, max_gap=750):
    """Rpm steps from idle to the top of the bank (inclusive), each loop pitched at most about +-6 %
    (neighbours a ratio apart) and never more than max_gap rpm apart. Evenly geometric when that
    already keeps the gaps short enough; otherwise evenly spaced on a scale that is logarithmic low
    down and linear above the rpm where the ratio would open a gap wider than max_gap."""
    if 'steps' in e:
        # an explicit list (a governed machine heard only round its working speed)
        return [int(r) for r in e['steps']]
    lo, hi, ratio = e['idle'], e['top'], e['ratio']
    n = max(1, math.ceil(math.log(hi / lo) / math.log(ratio)))
    geo = [lo * (hi / lo) ** (k / n) for k in range(n + 1)]
    if max(b - a for a, b in zip(geo, geo[1:])) <= max_gap:
        return [int(round(v / 10.0) * 10) for v in geo]
    k = math.log(ratio)
    knee = max_gap / (ratio - 1)

    def u(r):
        return math.log(r) / k if r <= knee else math.log(knee) / k + (r - knee) * (ratio - 1) / (max_gap * k)

    def u_inv(v):
        uk = math.log(knee) / k
        return math.exp(v * k) if v <= uk else knee + (v - uk) * max_gap * k / (ratio - 1)

    m = max(1, math.ceil(u(hi) - u(lo)))
    return [int(round(u_inv(u(lo) + j * (u(hi) - u(lo)) / m) / 10.0) * 10) for j in range(m + 1)]


def make_plan(eid):
    e = TABLE[eid]
    if e['offMode'] == 'light':
        return make_plan_light(eid)
    steps = rpm_steps(e)
    idle = e['idle']
    it = e.get('idleThrottle', 0.0)
    fuelcut = e['offMode'] == 'fuelcut'
    p = ['# generated by make_banks.py', 'throttle 0']
    # cranking on the starter, no spark
    p += ['starter on', 'take crank', 'sim 2.6', 'end', 'starter off', 'sim 1.5']
    # start: crank, catch, flare, settle to idle (a high-compression single that kicks back at its
    # first firings is taken by the dyno while the starter turns it forwards: see forward_grab)
    if e.get('forwardGrab'):
        p += ['take start', *forward_grab(), f'throttle {it}']
    else:
        p += ['ignition on', f'throttle {it}', 'starter on', 'take start', f'waitrpm {e["catch"]} 5', 'starter off', 'dyno grab']
    p += [f'dyno ramp {idle * e["flare"]:.0f} {e.get("catchRamp", 0.22)}', f'dyno ramp {idle} 0.9', 'sim 0.9', 'end']
    for r in steps:
        p += [f'dyno ramp {r} 0.35', 'ignition on', 'throttle 1 8', f'sim {SETTLE_ON}', f'take on_{r:05d}', f'sim {TAKE}', 'end', f'status on_{r}']
        if r == steps[0]:
            p += [f'throttle {it} 8']
        elif fuelcut:
            p += ['ignition off']
        else:
            p += ['throttle 0 8']
        p += [f'sim {SETTLE_OFF}', f'take off_{r:05d}', f'sim {TAKE}', 'end', f'status off_{r}', 'ignition on']
    # free revving against the rev limiter
    p += [f'dyno ramp {e["redline"] * 0.92:.0f} 0.4', 'throttle 1', 'dyno off', 'sim 1.2', 'take limiter', 'sim 2.0', 'end', 'status limiter']
    # back to idle, then switch off
    p += [f'throttle {it} 6', 'dyno grab', f'dyno ramp {idle} 1.2', 'sim 1.2', 'take shutdown', 'sim 0.25', 'dyno off', 'ignition off',
          f'sim {e.get("shutdownSeconds", 3.0)}', 'end', 'status shutdown']
    # restart, pull away with too little throttle and too much load: a stall
    if e.get('forwardGrab'):
        p += ['sim 0.5', *forward_grab(), f'throttle {it}']
    else:
        p += ['ignition on', 'starter on', f'waitrpm {e["catch"]} 5', 'starter off', 'dyno grab']
    p += [f'dyno ramp {idle} 0.6', 'sim 1.4', 'status restarted',
          'take stall', 'sim 0.3', 'throttle 0.15 2', f'dyno ramp {idle * 0.45:.0f} 0.45', 'dyno ramp 0 0.3', 'ignition off', 'dyno off', 'sim 1.3', 'end', 'status stall']
    return '\n'.join(p) + '\n'


def forward_grab():
    """Hand the crank to the dyno while the starter (here: the rope) turns it smoothly forwards with
    the air shut. A high-compression single kicks back at its first firings, and the dyno holds
    whichever way the crank happens to turn (the rpm the recorder reads is unsigned), so it must
    never take hold during a kick-back: it would drive the engine backwards and nothing would fire."""
    return ['ignition off', 'throttle 0', 'starter on', 'sim 0.35', 'dyno grab', 'starter off', 'ignition on']


def make_plan_light(eid):
    """A governed machine that never coasts (the generator): 'off' is a light-load run (spark on,
    the rack at offThrottle) at every step, the crank is a hand pull with the air open (a diesel has
    no throttle: every compression thumps), and there is no rev-limiter take."""
    e = TABLE[eid]
    steps = rpm_steps(e)
    idle = e['idle']
    it = e.get('idleThrottle', 0.0)
    light = e['offThrottle']
    p = ['# generated by make_banks.py (light-load machine)', f'throttle {e.get("crankThrottle", 1.0)}']
    # the pull: the rope spins it over its compressions, no fuel
    p += ['starter on', 'take crank', 'sim 2.6', 'end', 'starter off', 'sim 1.5']
    # start: spun on the rope, taken by the dyno, the rack opens: first firings, the run up to speed
    p += ['take start', *forward_grab(), 'throttle 1', f'dyno ramp {idle * e["flare"]:.0f} {e.get("catchRamp", 0.22)}',
          f'throttle {it} 4', f'dyno ramp {idle} 0.9', 'sim 0.9', 'end', 'status started']
    for r in steps:
        p += [f'dyno ramp {r} 0.35', 'ignition on', 'throttle 1 8', f'sim {SETTLE_ON}', f'take on_{r:05d}', f'sim {TAKE}', 'end', f'status on_{r}']
        p += [f'throttle {light} 8', f'sim {SETTLE_OFF}', f'take off_{r:05d}', f'sim {TAKE}', 'end', f'status off_{r}']
    if e.get('limiterTake', True):
        p += [f'dyno ramp {e["redline"] * 0.92:.0f} 0.4', 'throttle 1', 'dyno off', 'sim 1.2', 'take limiter', 'sim 2.0', 'end', 'status limiter']
    # back to the governed speed at light load, then the fuel cut: it runs down on its flywheel
    p += [f'throttle {it} 6', 'dyno grab', f'dyno ramp {idle} 1.2', 'sim 1.2', 'take shutdown', 'sim 0.25', 'dyno off', 'ignition off',
          f'sim {e.get("shutdownSeconds", 3.0)}', 'end', 'status shutdown']
    # restarted, then too much load: the governor opens the rack wide and it still drags down
    p += ['sim 0.5', *forward_grab(), f'throttle {it}', f'dyno ramp {idle} 0.8', 'sim 1.4', 'status restarted',
          'take stall', 'sim 0.3', f'throttle {e.get("stallThrottle", 0.15)} 4', f'dyno ramp {idle * 0.45:.0f} 0.45', 'dyno ramp 0 0.3',
          'ignition off', 'dyno off', 'sim 1.3', 'end', 'status stall']
    return '\n'.join(p) + '\n'


def recorder():
    return os.path.join(ESIM, 'build', 'esim_render.exe')


def record_one(eid):
    d = os.path.join(RAW, eid)
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)
    plan = os.path.join(d, 'plan.txt')
    open(plan, 'w').write(make_plan(eid))
    log = open(os.path.join(d, 'record.log'), 'w')
    r = subprocess.run([recorder(), '--es-root', os.path.join(ESIM, 'patched'), '--engine', os.path.join(HERE, 'engines', eid + '.mr'),
                        '--plan', plan, '--out', d], stdout=log, stderr=subprocess.STDOUT, timeout=7200)
    log.close()
    return eid, r.returncode


def cmd_record(ids):
    with ThreadPoolExecutor(max_workers=len(ids)) as ex:
        for eid, rc in ex.map(record_one, ids):
            print(f'{eid}: recorder exit {rc}; log {os.path.join(RAW, eid, "record.log")}')


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in ('record', 'build', 'all', 'plan'):
        print(__doc__)
        sys.exit(2)
    ids = sys.argv[2:] or list(TABLE)
    if sys.argv[1] == 'plan':
        for eid in ids:
            print(f'--- {eid}: {rpm_steps(TABLE[eid])}')
        return
    if sys.argv[1] in ('record', 'all'):
        cmd_record(ids)
    if sys.argv[1] in ('build', 'all'):
        # (run with python -I: the script's own directory is not on the path by itself)
        sys.path.insert(0, HERE)
        import bank_build
        bank_build.build(ids, TABLE, RAW, OUT)


if __name__ == '__main__':
    main()
