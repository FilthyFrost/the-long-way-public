"""ModCar engine banks: record every engine with the headless Engine Simulator recorder and cut the
takes into seamless loops and one-shots for src/game/modcar/engineAudio.ts.

    python -I tools/enginesim/make_banks.py record [ids...]   # run the recorder (parallel)
    python -I tools/enginesim/make_banks.py build  [ids...]   # cut, layer, level, encode, manifest
    python -I tools/enginesim/make_banks.py all    [ids...]

Paths (environment, defaults in brackets):
    MODCAR_ESIM      recorder build dir from prepare.mjs   [D:/modcar-scratch/sound/esim]
    MODCAR_RAW       raw takes                              [D:/modcar-scratch/sound/raw]
    MODCAR_FFMPEG    ffmpeg.exe                             [found on PATH or under D:/modcar-scratch/sound/dl-ffmpeg]

Every steady take is recorded with the dynamometer holding the crank speed, so nothing stalls and
the rpm of each loop is exact: 'on' = throttle wide open (the dyno absorbs the power), 'off' = the
overrun (throttle shut and spark on for the petrol engines; air open and fuel cut for the diesels),
which at the idle step is the idle itself.
"""
import glob
import json
import math
import os
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
ESIM = os.environ.get('MODCAR_ESIM', r'D:\modcar-scratch\sound\esim')
RAW = os.environ.get('MODCAR_RAW', r'D:\modcar-scratch\sound\raw')
OUT = os.path.join(REPO, 'public', 'audio', 'modcar', 'engines')
TABLE = json.load(open(os.path.join(HERE, 'engines.json'), encoding='utf8'))['engines']

SETTLE_ON = 1.2
SETTLE_OFF = 1.2
TAKE = 3.4


def rpm_steps(e):
    """Geometric rpm steps from idle to the top of the bank (inclusive)."""
    lo, hi, ratio = e['idle'], e['top'], e['ratio']
    n = max(1, math.ceil(math.log(hi / lo) / math.log(ratio)))
    return [int(round(lo * (hi / lo) ** (k / n) / 10.0) * 10) for k in range(n + 1)]


def make_plan(eid):
    e = TABLE[eid]
    steps = rpm_steps(e)
    idle = e['idle']
    it = e.get('idleThrottle', 0.0)
    fuelcut = e['offMode'] == 'fuelcut'
    p = ['# generated by make_banks.py', 'throttle 0']
    # cranking on the starter, no spark
    p += ['starter on', 'take crank', 'sim 2.6', 'end', 'starter off', 'sim 1.5']
    # start: crank, catch, flare, settle to idle
    p += ['ignition on', f'throttle {it}', 'starter on', 'take start', f'waitrpm {e["catch"]} 5', 'starter off',
          'dyno grab', f'dyno ramp {idle * e["flare"]:.0f} 0.22', f'dyno ramp {idle} 0.9', 'sim 0.9', 'end']
    for r in steps:
        p += [f'dyno ramp {r} 0.35', 'ignition on', 'throttle 1 8', f'sim {SETTLE_ON}', f'take on_{r:05d}', f'sim {TAKE}', 'end', f'status on_{r}']
        if r == steps[0]:
            p += [f'throttle {it} 8']
        elif fuelcut:
            p += ['ignition off']
        else:
            p += ['throttle 0 8']
        p += [f'sim {SETTLE_OFF}', f'take off_{r:05d}', f'sim {TAKE}', 'end', f'status off_{r}', 'ignition on']
    # free revving against the rev limiter
    p += [f'dyno ramp {e["redline"] * 0.92:.0f} 0.4', 'throttle 1', 'dyno off', 'sim 1.2', 'take limiter', 'sim 2.0', 'end', 'status limiter']
    # back to idle, then switch off
    p += [f'throttle {it} 6', 'dyno grab', f'dyno ramp {idle} 1.2', 'sim 1.2', 'take shutdown', 'sim 0.25', 'dyno off', 'ignition off', 'sim 3.0', 'end', 'status shutdown']
    # restart, pull away with too little throttle and too much load: a stall
    p += ['ignition on', 'starter on', f'waitrpm {e["catch"]} 5', 'starter off', 'dyno grab', f'dyno ramp {idle} 0.6', 'sim 1.4', 'status restarted',
          'take stall', 'sim 0.3', 'throttle 0.15 2', f'dyno ramp {idle * 0.45:.0f} 0.45', 'dyno ramp 0 0.3', 'ignition off', 'dyno off', 'sim 1.3', 'end', 'status stall']
    return '\n'.join(p) + '\n'


def recorder():
    return os.path.join(ESIM, 'build', 'esim_render.exe')


def record_one(eid):
    d = os.path.join(RAW, eid)
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)
    plan = os.path.join(d, 'plan.txt')
    open(plan, 'w').write(make_plan(eid))
    log = open(os.path.join(d, 'record.log'), 'w')
    r = subprocess.run([recorder(), '--es-root', os.path.join(ESIM, 'patched'), '--engine', os.path.join(HERE, 'engines', eid + '.mr'),
                        '--plan', plan, '--out', d], stdout=log, stderr=subprocess.STDOUT, timeout=7200)
    log.close()
    return eid, r.returncode


def cmd_record(ids):
    with ThreadPoolExecutor(max_workers=len(ids)) as ex:
        for eid, rc in ex.map(record_one, ids):
            print(f'{eid}: recorder exit {rc}; log {os.path.join(RAW, eid, "record.log")}')


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in ('record', 'build', 'all', 'plan'):
        print(__doc__)
        sys.exit(2)
    ids = sys.argv[2:] or list(TABLE)
    if sys.argv[1] == 'plan':
        for eid in ids:
            print(f'--- {eid}: {rpm_steps(TABLE[eid])}')
        return
    if sys.argv[1] in ('record', 'all'):
        cmd_record(ids)
    if sys.argv[1] in ('build', 'all'):
        # (run with python -I: the script's own directory is not on the path by itself)
        sys.path.insert(0, HERE)
        import bank_build
        bank_build.build(ids, TABLE, RAW, OUT)


if __name__ == '__main__':
    main()
