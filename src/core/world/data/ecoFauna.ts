/** Roadside observation candidates. Local calendar months; see docs/V3/research/animals-crops.md. */
type Time = 'day' | 'night' | 'twilight' | 'variable';
type Habitat = 'forest-edge' | 'scree' | 'meadow' | 'wetland' | 'cliff' | 'scrub' | 'tundra' | 'riparian' | 'farm' | 'savanna' | 'water-edge' | 'forest' | 'shore';
export interface RoadAnimal {
  name: string;
  taxon: string;
  /** Typical on-screen group, not an estimate of total herd size. */
  visibleGroup: readonly [number, number];
  social: string;
  months: readonly number[];
  time: Time;
  habitat: Habitat;
  road: string;
  footRisk: string;
  /** Regional use, never a park-specific permission or harvest season. */
  use: 'domestic' | 'regional-game' | 'conservation' | 'unverified';
}
export interface RoadFish {
  name: string;
  taxon: string;
  water: 'river' | 'lake' | 'coast' | 'fjord' | 'estuary' | 'paddy';
  months: readonly number[];
  time: Time;
  habitat: string;
  use: 'regional-fishery' | 'aquaculture' | 'unverified';
}
export interface RoadCrop {
  name: string;
  habitat: string;
  /** Null for established perennial orchards. */
  sowMonths: readonly number[] | null;
  harvestMonths: readonly number[];
  appearance: string;
}
export interface RoadFood {
  name: string;
  taxon: string;
  /** Null where the existing catalogue has no suitable kind. */
  forageId: string | null;
  months: readonly number[];
  habitat: string;
  caution: string;
}

